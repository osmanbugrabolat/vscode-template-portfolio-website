// Generates supabase/seed-cms.sql from supabase/content/cms.json.
// Usage: npm run cms:seed
// Every insert uses ON CONFLICT DO NOTHING, so re-running the seed never
// overwrites content that was later edited in the admin panel.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const cms = JSON.parse(readFileSync(join(root, "supabase/content/cms.json"), "utf8"));

/** Deterministic UUID (v5-like) so seeded rows keep stable ids across environments. */
function uuidFor(namespace, key) {
  const h = createHash("sha1").update(`${namespace}:${key}`).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-${((parseInt(h[16], 16) & 0x3) | 0x8).toString(16)}${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

const lit = (v) => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  if (Array.isArray(v)) return `array[${v.map(lit).join(", ")}]::text[]`;
  return `'${String(v).replaceAll("'", "''")}'`;
};

function insert(table, row, conflict = "id") {
  const cols = Object.keys(row);
  return `insert into public.${table} (${cols.join(", ")}) values (${cols.map((c) => lit(row[c])).join(", ")}) on conflict (${conflict}) do nothing;`;
}

const lines = [
  "-- Generated by scripts/generate-cms-seed.mjs from supabase/content/cms.json.",
  "-- Initial content only: ON CONFLICT DO NOTHING keeps later admin edits intact.",
  "begin;",
  "",
  insert("site_settings", { id: 1, ...cms.settings }),
  "",
];

const keys = new Set(cms.nodes.map((n) => n.key));
for (const node of cms.nodes) {
  if (node.parent && !keys.has(node.parent)) throw new Error(`Unknown parent ${node.parent} for ${node.key}`);
  const { key, parent, ...rest } = node;
  lines.push(
    insert("explorer_nodes", {
      id: uuidFor("node", key),
      parent_id: parent ? uuidFor("node", parent) : null,
      ...Object.fromEntries(Object.entries(rest).filter(([, v]) => v !== undefined)),
    }),
  );
}
lines.push("");

for (const category of cms.skill_categories) {
  const { skills, ...rest } = category;
  const categoryId = uuidFor("skill_category", category.key);
  lines.push(insert("skill_categories", { id: categoryId, ...rest }));
  for (const skill of skills) {
    lines.push(insert("skills", { id: uuidFor("skill", `${category.key}:${skill.name}`), category_id: categoryId, ...skill }));
  }
}
lines.push("");

for (const exp of cms.experiences) {
  lines.push(insert("experiences", { id: uuidFor("experience", `${exp.company}:${exp.sort_order}`), ...exp }));
}

lines.push("", "commit;", "");
writeFileSync(join(root, "supabase/seed-cms.sql"), lines.join("\n"));
console.log(`supabase/seed-cms.sql: ${cms.nodes.length} nodes, ${cms.skill_categories.length} skill categories, ${cms.experiences.length} experiences`);
