// Generates supabase/seed.sql from src/lib/chatbot/knowledge.json.
// Usage: npm run chat:seed
// The seed is idempotent: re-running it updates existing intents and
// replaces their patterns, so it is safe to paste into the SQL Editor again.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { intents } = JSON.parse(readFileSync(join(root, "src/lib/chatbot/knowledge.json"), "utf8"));

const str = (value) => `'${String(value).replaceAll("'", "''")}'`;
const textArray = (values) => `array[${values.map(str).join(", ")}]::text[]`;
const jsonb = (value) => `${str(JSON.stringify(value))}::jsonb`;

const ids = new Set(intents.map((i) => i.id));
for (const intent of intents) {
  for (const id of intent.followUps) {
    if (!ids.has(id)) throw new Error(`Intent "${intent.id}" has unknown follow-up "${id}"`);
  }
}

const lines = [
  "-- Generated by scripts/generate-chat-seed.mjs from src/lib/chatbot/knowledge.json.",
  "-- Do not edit by hand; edit the JSON and run `npm run chat:seed`.",
  "begin;",
  "",
];

for (const i of intents) {
  lines.push(
    `insert into public.chat_intents (id, category, priority, title_tr, title_en, answer_tr, answer_en, keywords, links, follow_ups)`,
    `values (${[
      str(i.id),
      str(i.category),
      i.priority,
      str(i.title.tr),
      str(i.title.en),
      str(i.answer.tr),
      str(i.answer.en),
      textArray(i.keywords),
      jsonb(i.links),
      textArray(i.followUps),
    ].join(", ")})`,
    `on conflict (id) do update set category = excluded.category, priority = excluded.priority,`,
    `  title_tr = excluded.title_tr, title_en = excluded.title_en, answer_tr = excluded.answer_tr,`,
    `  answer_en = excluded.answer_en, keywords = excluded.keywords, links = excluded.links,`,
    `  follow_ups = excluded.follow_ups;`,
    `delete from public.chat_patterns where intent_id = ${str(i.id)};`,
  );
  const rows = ["tr", "en"].flatMap((lang) => i.patterns[lang].map((p) => `(${str(i.id)}, '${lang}', ${str(p)})`));
  if (rows.length) {
    lines.push(`insert into public.chat_patterns (intent_id, lang, pattern) values`, `  ${rows.join(",\n  ")}`, `on conflict do nothing;`);
  }
  lines.push("");
}

lines.push("commit;", "");
writeFileSync(join(root, "supabase/seed.sql"), lines.join("\n"));

const patternCount = intents.reduce((n, i) => n + i.patterns.tr.length + i.patterns.en.length, 0);
console.log(`supabase/seed.sql: ${intents.length} intents, ${patternCount} patterns`);
